"""Noms de la liste des secrets de Farore et textes du suivi des codes, dans la
langue choisie : écrit oracles-disasm/code/crossworldSecretNames.s.

Les noms viennent de la ROM Seasons Europe (5 tables en banque 2, une par
langue, comme le reste du jeu). Les textes du suivi sont propres au projet.

Usage : python fr/make_secret_names.py [--lang=fr]
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lang as langmod

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEASONS_EU = os.path.join(ROOT, 'Legend of Zelda, The - Oracle of Seasons (Europe) (En,Fr,De,Es,It).gbc')
OUT = os.path.join(ROOT, 'oracles-disasm', 'code', 'crossworldSecretNames.s')

LANG_TABLES = 0x8f47   # 5 pointeurs (EN FR DE IT ES) vers les tables de noms, banque 2
NUM_NAMES = 0x1a

# Lettres de la police européenne
CHARS = {'à': 0xa0, 'â': 0xa1, 'ä': 0xa2, 'ç': 0xa4, 'è': 0xa5, 'é': 0xa6, 'ê': 0xa7,
         'î': 0xa9, 'ù': 0xae, 'û': 0xaf, 'ü': 0xb0, 'ô': 0xd0, 'í': 0xd3, 'ß': 0x91,
         'À': 0x80}

# Textes du suivi. Ligne du menu : 16 caractères max ; cadre du bas : 2 lignes
# de 11 caractères (le 12e est caché par le bord).
#   unavailable : ligne affichée dans l'aventure 1 pas encore finie
#   finish      : cadre du bas avec cette ligne
#   none        : code pas encore reçu
#   reward      : aventure 1, récompense à prendre ici
#   farore1     : aventure 1, récompense prise, retour chez Farore (aventure 2)
#   tell        : aventure 2, code reçu, à donner dans l'aventure 1
#   farore2     : aventure 2, Farore a un cadeau
#   done        : échange terminé
TEXTS = {
    'en': dict(unavailable='Not available', finish=('Finish', 'adventure 1'),
               none=('No secret', 'yet'), reward=('Reward to', 'collect'),
               farore1=('See Farore', 'adventure 2'), tell=('Tell it in', 'adventure 1'),
               farore2=('Farore has', 'a gift'), done=('Complete', '')),
    'fr': dict(unavailable='Non disponible', finish=('Finir', 'aventure 1'),
               none=('Code pas', 'encore reçu'), reward=('Récompense', 'à récupérer'),
               farore1=('Voir Farore', 'aventure 2'), tell=('À donner', 'aventure 1'),
               farore2=('Farore a', 'un cadeau'), done=('Terminé', '')),
    'de': dict(unavailable='Nicht verfügbar', finish=('Beende erst', 'Abenteuer 1'),
               none=('Geheimnis', 'fehlt noch'), reward=('Belohnung', 'abholen'),
               farore1=('Zu Farore', 'Abenteuer 2'), tell=('Weitergeben', 'Abenteuer 1'),
               farore2=('Geschenk', 'bei Farore'), done=('Erledigt', '')),
    'it': dict(unavailable='Non disponibile', finish=('Completa', 'avventura 1'),
               none=('Segreto non', 'ricevuto'), reward=('Ricompensa', 'da ritirare'),
               farore1=('Da Farore', 'avventura 2'), tell=('Da dire in', 'avventura 1'),
               farore2=('Farore ha', 'un regalo'), done=('Completato', '')),
    'es': dict(unavailable='No disponible', finish=('Termina la', 'aventura 1'),
               none=('Secreto', 'sin recibir'), reward=('Recompensa', 'por recoger'),
               farore1=('Ve a Farore', 'aventura 2'), tell=('Dilo en la', 'aventura 1'),
               farore2=('Regalo de', 'Farore'), done=('Completado', '')),
}
# Ordre attendu par code/crossworldSecretList.s (FR_TRACKER_TXT_*)
BOX_ORDER = ['none', 'reward', 'farore1', 'tell', 'farore2', 'done', 'finish']


def encode(s):
    out = []
    for ch in s:
        if ch in CHARS:
            out.append(CHARS[ch])
        else:
            assert ord(ch) < 0x80, ch
            out.append(ord(ch))
    return out


def center(chars, width=11):
    left = (width - len(chars)) // 2
    return [0x20] * left + chars + [0x20] * (12 - left - len(chars))


def db(values):
    return '\t.db ' + ' '.join('$%02x' % v for v in values)


def read_names(lang_index):
    rom = open(SEASONS_EU, 'rb').read()
    table = struct.unpack_from('<H', rom, LANG_TABLES + 2 * lang_index)[0]
    off = 0x8000 + table - 0x4000
    names = []
    for i in range(NUM_NAMES):
        p = 0x8000 + struct.unpack_from('<H', rom, off + 2 * i)[0] - 0x4000
        end = rom.index(b'\x00', p)
        names.append(list(rom[p:end]))
    assert bytes(names[1]) == b'--------', names[1]
    return names


def main():
    code, index = langmod.current()
    names = read_names(index)
    t = TEXTS[code]
    lines = ['; Generated by fr/make_secret_names.py (language: %s), do not edit.' % code, '',
             "; Names for Farore's secret list (was _secretTextTable in bank 2)",
             'frSecretTextTable:']
    lines += ['\t.dw @name%02x' % i for i in range(NUM_NAMES)]
    for i, n in enumerate(names):
        lines.append('@name%02x:' % i)
        lines.append(db(n + [0]))
    lines += ['', '; Tracker: row shown when the tracker is not available yet',
              'frTrackerUnavailableRow:']
    row = encode(t['unavailable'])
    assert len(row) <= 16, t['unavailable']
    lines.append(db(row + [0]))
    lines += ['', '; Tracker: bottom box texts (2 lines of 12 characters, FR_TRACKER_TXT_*)', 'frTrackerBoxTexts:']
    lines += ['\t.dw @%s' % k for k in BOX_ORDER]
    for k in BOX_ORDER:
        a, b = t[k]
        ea, eb = encode(a), encode(b)
        assert len(ea) <= 11 and len(eb) <= 11, (k, a, b)
        lines.append('@%s:' % k)
        lines.append(db(center(ea) + center(eb)))
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    print(OUT, code)


if __name__ == '__main__':
    main()
